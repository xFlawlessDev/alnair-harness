<script lang="ts">
	/**
	 * One rendered guide page: the article, an "on this page" rail on the right,
	 * and the previous/next pair that keeps a reader moving in the guide's order.
	 *
	 * The rail is the page's primary wayfinding while reading a long chapter, so
	 * it sits where the eye is when the reader loses their place — and it marks
	 * the section currently on screen rather than only offering a jump.
	 */
	import { docsCopy } from '$lib/docs/copy';
	import type { DocMeta } from '$lib/docs/source';
	import type { Heading } from '$lib/docs/render';
	import type { Locale } from '$lib/i18n';
	import Rich from '$lib/components/Rich.svelte';

	let {
		locale,
		doc,
		html,
		headings,
		minutes,
		docs
	}: {
		locale: Locale;
		doc: DocMeta;
		html: string;
		headings: Heading[];
		minutes: number;
		docs: DocMeta[];
	} = $props();

	const copy = $derived(docsCopy[locale]);
	const base = $derived(locale === 'en' ? '/docs/' : '/id/docs/');

	/** Only `##`: the `h1` is the page title, which the header already shows. */
	const toc = $derived(headings.filter((heading) => heading.level === 2));

	const index = $derived(docs.findIndex((entry) => entry.slug === doc.slug));
	const previous = $derived(index > 0 ? docs[index - 1] : undefined);
	const next = $derived(index >= 0 && index < docs.length - 1 ? docs[index + 1] : undefined);

	/*
	 * The section marker.
	 *
	 * The observer band is a thin strip near the top of the viewport, so exactly
	 * one heading is "current" at a time and it is the one the reader has just
	 * scrolled to. Without JavaScript nothing here runs and the rail is a plain
	 * list of working anchors, which is the honest fallback.
	 */
	let activeId = $state('');

	$effect(() => {
		const targets = toc
			.map((heading) => document.getElementById(heading.id))
			.filter((node): node is HTMLElement => node !== null);

		if (targets.length === 0) return;

		activeId = targets[0].id;

		// A plain Set, not SvelteMap: this only records which observer entries
		// fired, and nothing renders from it — the reactive value is `activeId`.
		const seen = new Set<string>();
		const observer = new IntersectionObserver(
			(entries) => {
				for (const entry of entries) {
					if (entry.isIntersecting) seen.add(entry.target.id);
					else seen.delete(entry.target.id);
				}

				// The band can hold more than one heading when they are close
				// together; the first in document order is the one being read.
				const current = targets.find((target) => seen.has(target.id));
				if (current) activeId = current.id;
			},
			// A thin band below the sticky header. `rootMargin` takes either
			// absolute lengths or percentages — never both — so this stays in
			// percentages, which is also what keeps it right across viewports.
			{ rootMargin: '-8% 0px -72% 0px', threshold: 0 }
		);

		for (const target of targets) observer.observe(target);

		return () => observer.disconnect();
	});
</script>

<article class="doc">
	<header class="head">
		<nav class="crumbs" aria-label="Breadcrumb">
			<a href={base}>{copy.title}</a>
			<span aria-hidden="true">/</span>
			<span>{doc.title}</span>
		</nav>

		<h1>{doc.title}</h1>
		<p class="desc"><Rich text={doc.description} /></p>
		<p class="meta">{copy.readTime(minutes)}</p>
	</header>

	{#if toc.length > 1}
		<nav class="toc" aria-label={copy.onThisPage}>
			<span class="toc-label">{copy.onThisPage}</span>
			<ul>
				{#each toc as heading (heading.id)}
					<li>
						<a
							href="#{heading.id}"
							class:active={heading.id === activeId}
							aria-current={heading.id === activeId ? 'location' : undefined}
						>
							{heading.text}
						</a>
					</li>
				{/each}
			</ul>
		</nav>
	{/if}

	<!-- The HTML is generated by `render_doc` from files in this repository,
	     with no author-supplied markup path: marked's renderer escapes text and
	     the only raw HTML in the guide is a code fence. -->
	<div class="prose">{@html html}</div>

	<nav class="pager" aria-label="{copy.previous} / {copy.next}">
		{#if previous}
			<a class="pager-link prev" href="{base}{previous.slug}/">
				<span class="dir">{copy.previous}</span>
				<span class="name">{previous.title}</span>
			</a>
		{:else}
			<span></span>
		{/if}

		{#if next}
			<a class="pager-link next" href="{base}{next.slug}/">
				<span class="dir">{copy.next}</span>
				<span class="name">{next.title}</span>
			</a>
		{/if}
	</nav>
</article>

